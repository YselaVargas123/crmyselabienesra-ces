const { PGlite } = require('@electric-sql/pglite');
const fs = require('node:fs');
const assert = require('node:assert/strict');
async function main() {
 const db = new PGlite();
 await db.exec(`
 create role anon; create role authenticated;
 create schema auth; create schema storage;
 create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth,public,storage to authenticated,anon;
 create table public.profiles(id uuid primary key,active boolean,role text);
 create table public.contacts(id uuid primary key,first_name text,last_name text,whatsapp text,phone text);
 create table public.properties(id uuid primary key,title text);
 create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table storage.objects(id uuid primary key,bucket_id text,name text);
 create function storage.foldername(name text) returns text[] language sql immutable as $$select string_to_array(name,'/')$$;
 grant select on public.profiles,public.contacts to authenticated;
 insert into auth.users values ('00000000-0000-4000-8000-000000000001'),('00000000-0000-4000-8000-000000000002'),('00000000-0000-4000-8000-000000000003');
 insert into profiles values ('00000000-0000-4000-8000-000000000001',true,'agente'),('00000000-0000-4000-8000-000000000002',true,'asistente'),('00000000-0000-4000-8000-000000000003',false,'agente');
 insert into contacts values ('00000000-0000-4000-8000-000000000004','Contacto','Existente','77123456',null);
 insert into properties values ('00000000-0000-4000-8000-000000000005','Propiedad a conservar');
 `);
 await db.exec(fs.readFileSync('database/whatsapp-local.sql','utf8'));
 console.log('OK: migración completa ejecutada en PostgreSQL temporal');
 const original = await db.query('select title from properties'); assert.equal(original.rows[0].title,'Propiedad a conservar');
 assert.equal((await db.query('select count(*)::int as n from contacts')).rows[0].n,1);
 async function asUser(id) { await db.exec(`reset role; set role authenticated; select set_config('request.jwt.claim.sub','00000000-0000-4000-8000-${id.padStart(12,'0')}',false)`); }
 await asUser('1');
 const line=(await db.query("insert into crm_wa_devices(name) values('Prueba') returning id")).rows[0].id;
 const worker='00000000-0000-4000-8000-000000000010';
 assert.equal((await db.query('select crm_wa_lease($1,$2) as ok',[line,worker])).rows[0].ok,true);
 assert.equal((await db.query('select crm_wa_lease($1,$2) as ok',[line,'00000000-0000-4000-8000-000000000011'])).rows[0].ok,false);
 const hilo=(await db.query("select crm_wa_open_thread($1,'00000000-0000-4000-8000-000000000004') as id",[line])).rows[0].id;
 const hilo2=(await db.query("select crm_wa_open_thread($1,'00000000-0000-4000-8000-000000000004') as id",[line])).rows[0].id;
 assert.equal(hilo,hilo2);
 console.log('OK: contacto reutilizado sin duplicar; segunda computadora no puede tomar línea activa');
 await asUser('2');
 await assert.rejects(db.query("insert into crm_wa_devices(name) values('No autorizado')"));
 await assert.rejects(db.query("insert into crm_wa_commands(device_id,action) values($1,'connect')",[line]));
 await db.query("insert into crm_wa_commands(device_id,action,payload) values($1,'send',$2)",[line,JSON.stringify({thread_id:hilo,body:'Hola'})]);
 const cancelled=(await db.query("insert into crm_wa_commands(device_id,action,payload) values($1,'send',$2) returning id",[line,JSON.stringify({thread_id:hilo,body:'Cancelar antes de enviar'})])).rows[0].id;
 assert.equal((await db.query('select crm_wa_cancel($1) as ok',[cancelled])).rows[0].ok,true);
 assert.equal((await db.query('select crm_wa_cancel($1) as ok',[cancelled])).rows[0].ok,false);
 await asUser('1');
 assert.equal((await db.query('select * from crm_wa_claim($1,$2)',[line,worker])).rows.length,0);
 await db.query("update crm_wa_devices set state='connected' where id=$1",[line]);
 assert.equal((await db.query('select * from crm_wa_claim($1,$2)',[line,worker])).rows.length,1);
 const claimed=(await db.query("select id from crm_wa_commands where state='processing'")).rows[0].id;
 assert.equal((await db.query('select crm_wa_requester_active($1) as ok',[claimed])).rows[0].ok,true);
 assert.equal((await db.query('select * from crm_wa_claim($1,$2)',[line,worker])).rows.length,0);
 await db.query("update crm_wa_commands set claimed_at=now()-interval '3 minutes' where device_id=$1",[line]);
 await db.query('select * from crm_wa_claim($1,$2)',[line,worker]);
 assert.equal((await db.query("select count(*)::int as n from crm_wa_commands where state='failed'")).rows[0].n,1);
 await db.query("insert into crm_wa_commands(device_id,action,payload,scheduled_at,expires_at) values($1,'send',$2,now()-interval '30 minutes',now()-interval '15 minutes')",[line,JSON.stringify({thread_id:hilo,body:'Este programado ya venció'})]);
 assert.equal((await db.query('select * from crm_wa_claim($1,$2)',[line,worker])).rows.length,0);
 assert.equal((await db.query("select count(*)::int as n from crm_wa_commands where state='failed'")).rows[0].n,2);
 console.log('OK: asistente puede solicitar mensajes; no puede vincular líneas; reclamo único y sin reenvío ciego tras cierre');
 await asUser('3');
 assert.equal((await db.query('select * from crm_wa_messages')).rows.length,0);
 assert.equal((await db.query('select * from crm_wa_devices')).rows.length,0);
 await db.exec('reset role; set role anon');
 await assert.rejects(db.query('select * from crm_wa_devices'));
 await db.exec('reset role');
 assert.equal((await db.query('select count(*)::int as n from contacts')).rows[0].n,1);
 assert.equal((await db.query('select title from properties')).rows[0].title,'Propiedad a conservar');
 console.log('OK: anónimos e inactivos bloqueados; datos inmobiliarios conservados');
 await db.close();
}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
